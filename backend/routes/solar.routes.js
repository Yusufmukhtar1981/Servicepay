router.patch("/admin/applications/:applicationId/recovery", protect, admins, controller.recovery);
router.post("/admin/finance/:financeId/recovery", protect, admins, controller.openRecoveryCase);
router.get("/admin/dashboard", protect, admins, controller.dashboard);
router.get("/admin/reports", protect, admins, controller.reports);
module.exports = router;