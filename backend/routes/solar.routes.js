router.get("/my-applications", protect, customerOnly, controller.myApplications);
router.get("/my-applications/:applicationId", protect, customerOnly, controller.getMyApplication);
router.post("/applications/:applicationId/pay-deposit", protect, customerOnly, controller.payDeposit);
router.post("/applications/:applicationId/payments", protect, customerOnly, controller.pay);
router.get("/my-finance", protect, customerOnly, controller.myFinance);
router.get("/finance/:financeId", protect, customerOnly, controller.getFinance);
router.get("/finance/:financeId/schedule", protect, customerOnly, controller.financeSchedule);
router.get("/finance/:financeId/payments", protect, customerOnly, controller.financePayments);
router.post("/finance/:financeId/pay", protect, customerOnly, controller.payFinance);
router.get("/admin/settings", protect, admins, controller.getSettings);
router.put("/admin/settings", protect, admins, controller.updateSettings);
router.post("/admin/packages", protect, admins, controller.createPackage);
router.patch("/admin/packages/:packageId", protect, admins, controller.updatePackage);
router.delete("/admin/packages/:packageId", protect, admins, controller.deletePackage);
router.get("/admin/applications", protect, admins, controller.adminApplications);
router.get("/admin/finance", protect, admins, controller.adminFinance);
